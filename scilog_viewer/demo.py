def _sentence(rng):
    p = rng.choice(PATTERNS)
    thing, thing2 = rng.sample(THINGS, 2)
    a = rng.uniform(-40, 40)
    out = p.format(
        thing=thing, thing2=thing2, Thing=thing.capitalize(), quality=rng.choice(QUALITIES),
        doing=rng.choice(DOINGS), unit=rng.choice(UNITS), num=f"{rng.uniform(-50, 500):.2f}".rstrip("0").rstrip("."),
        num2=f"{rng.uniform(0, 100):.1f}", a=f"{a:.1f}", b=f"{a + rng.uniform(1, 60):.1f}",
        step=f"{rng.uniform(0.01, 2):.2f}", n=rng.randint(2, 900), n2=rng.randint(2, 900),
        n3=rng.randint(2, 900), hour=f"{rng.randint(0, 23):02d}", minute=f"{rng.randint(0, 59):02d}")
    return out[0].upper() + out[1:]


def _words(rng, count):
    """A paragraph of about this many words (the real posts: 21 words in the middle, a few much longer)."""
    out = []
    while sum(len(s.split()) for s in out) < count:
        out.append(_sentence(rng))
    return " ".join(out)


