# -- the logbook -----------------------------------------------------------------------------

def _oid(rng):
    return "".join(rng.choice("0123456789abcdef") for _ in range(24))


def _iso(when):
    return time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime(when))


def _pick(rng, weighted):
    total = sum(w for _, w in weighted)
    r = rng.uniform(0, total)
    for value, w in weighted:
        r -= w
        if r <= 0:
            return value
    return weighted[-1][0]


def _table(rng):
    """The table an automatic scan report carries: seven rows, five columns."""
    head = ["step", "position", "i0", "signal", "ratio"]
    rows = ["<tr>" + "".join(f"<th>{h}</th>" for h in head) + "</tr>"]
    for i in range(6):
        cells = [str(i + 1), f"{rng.uniform(-20, 20):.3f}", f"{rng.uniform(1e3, 9e3):.0f}",
                 f"{rng.uniform(1, 500):.1f}", f"{rng.uniform(0, 1):.4f}"]
        rows.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return ("<figure class=\"table\"><table><tbody>" + "".join(rows) + "</tbody></table></figure>")


def _figure_html(rng, file_hash, width=None):
    """An image as SciLog's editor writes one (the file named by its hash)."""
    style = f' style="width:{width}%"' if width else ""
    return (f'<figure class="image{" image_resized" if width else ""}"{style}>'
            f'<img src="" title="{file_hash}"></figure>')


def make(where=None, posts=1729, seed=7, figures=80, quiet=False):
    """Write a made-up logbook into `where` (a folder): logbook.json and the
    figures beside it. Returns the folder. The same seed gives the same logbook."""
    where = Path(where or DEFAULT_DIR)
    (where / "files").mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    logbook_id = _oid(rng)

    # the pictures: a handful drawn here, shared out over the posts that have one
    pictures = []
    for i in range(figures):
        draw = FIGURES[i % len(FIGURES)]
        data = draw(rng)
        fid = _oid(rng)
        (where / "files" / f"{fid}.png").write_bytes(data)
        pictures.append(fid)
        if not quiet and (i + 1) % 20 == 0:
            print(f"  {i + 1}/{figures} figures drawn", flush=True)

    files = {fid: {"name": f"figure_{i:03d}.png", "type": "image/png", "path": f"files/{fid}.png"}
             for i, fid in enumerate(pictures)}

    # the days: the busiest ones in beamtime blocks, the quiet ones scattered between them
    shape = sorted((max(1, round(n * posts / sum(DAY_SHAPE))) for n in DAY_SHAPE), reverse=True)
    start = time.mktime((2026, 1, 12, 8, 0, 0, 0, 0, -1))
    span = 86                                           # three months, as the real one spans
    days, taken = [], set()
    for i, n in enumerate(shape[:9]):                   # the beamtimes: three days each
        offset = (i // 3) * 30 + i % 3
        days.append((offset, n))
        taken.add(offset)
    for n in shape[9:]:                                 # the quiet days, in between and after
        offset = rng.randrange(span)
        while offset in taken:
            offset = rng.randrange(span)
        taken.add(offset)
        days.append((offset, n))

    rows, written = [], 0
    for offset, count in sorted(days):
        when = start + offset * 86400
        for _ in range(count):
            when += rng.uniform(60, 240) if count > 60 else rng.uniform(600, 5400)
            rows.append(_post(rng, logbook_id, when, pictures, files, where))
            written += 1
            if not quiet and written % 500 == 0:
                print(f"  {written} posts", flush=True)

    # a few comments and replies, as the real one has
    for raw in rng.sample(rows, min(len(rows), max(1, round(len(rows) * 0.042)))):
        raw.setdefault("subsnippets", []).append(_child(rng, raw, "comment"))
    for raw in rng.sample(rows, min(len(rows), max(1, round(len(rows) * 0.01)))):
        raw.setdefault("subsnippets", []).append(_child(rng, raw, "quote"))

    book = {"id": logbook_id, "name": "26x_demo_p00000", "ownerGroup": "p00000", "location": "DEMO-BEAMLINE",
            "isPrivate": False, "description": "A made-up logbook: generated text and figures, nothing real.",
            "createdAt": _iso(start), "updatedAt": rows[-1]["createdAt"], "touchedAt": rows[-1]["createdAt"],
            "accessGroups": ["p00000"], "readACL": ["p00000"], "updateACL": ["p00000"]}
    tasks = [{"id": _oid(rng), "content": f"{rng.choice(DOINGS).capitalize()} the {rng.choice(THINGS)}",
              "isDone": rng.random() < 0.4, "defaultOrder": (i + 1) * 1_000_000, "parentId": logbook_id,
              "snippetType": "task", "createdBy": AUTHORS[1][0], "updatedBy": AUTHORS[1][0],
              "createdAt": _iso(start + i * 3600), "updatedAt": _iso(start + i * 3600)} for i in range(8)]
    (where / "logbook.json").write_text(json.dumps(
        {"made": "scilog_viewer.demo", "seed": seed, "logbook": book, "posts": rows, "tasks": tasks, "files": files}))
    if not quiet:
        size = sum(f.stat().st_size for f in where.rglob("*") if f.is_file())
        print(f"{len(rows)} posts, {len(pictures)} figures, {size / 1e6:.1f} MB in {where}", flush=True)
    return where


def _post(rng, logbook_id, when, pictures, files, where):
    kind = _pick(rng, KINDS)
    author = _pick(rng, AUTHORS)
    body, attached = [], []
    if "note" in kind or kind == "heading":
        level = rng.choice([1, 2, 2, 3, 3, 3])
        body.append(f"<h{level}>{rng.choice(HEADINGS)}</h{level}>")
    if "figure" in kind:
        for _ in range(1 if rng.random() < 0.8 else rng.randint(2, 4)):
            fid = rng.choice(pictures)
            file_hash = f"h{fid[:12]}"
            attached.append({"fileHash": file_hash, "fileId": fid, "fileExtension": "image/png",
                             "accessHash": file_hash})
            body.append(_figure_html(rng, file_hash, rng.choice([None, None, None, 30, 40, 50, 70])))
    if "scan" in kind:
        body.append(f"<h4>scan {rng.randint(100, 9999)} {rng.choice(THINGS)} "
                    f"{rng.uniform(-20, 20):.2f} to {rng.uniform(-20, 20):.2f}</h4>")
        body.append(_table(rng))
    if "scan" in kind or "data" in kind:
        name = f"scan{rng.randint(100, 9999)}.json"
        fid = _oid(rng)
        file_hash = f"h{fid[:12]}"
        files[fid] = {"name": name, "type": "file/json", "path": None, "size": rng.randint(2000, 90000)}
        attached.append({"fileHash": file_hash, "fileId": fid, "fileExtension": "file/json", "accessHash": file_hash})
        body.append(f'<p><a class="fileLink" target="_blank" href="file:{file_hash}">{name}</a></p>')
    if kind == "list":
        body.append("<ul>" + "".join(f"<li>{_sentence(rng)}</li>" for _ in range(rng.randint(2, 5))) + "</ul>")
    if kind != "figure only" and kind != "heading":
        # the real logbook: 21 words in the middle post, a few of several hundred. A whole
        # sentence is about ten, so the aim is set below what comes out.
        want = rng.randint(80, 340) if kind == "long" else max(4, int(rng.lognormvariate(2.5, 0.6)))
        for _ in range(1 if want < 60 else rng.randint(2, 4)):
            body.append(f"<p>{_words(rng, want if want < 60 else want // 3)}</p>")
    created = _iso(when)
    edited = rng.random() < 0.06
    return {"id": _oid(rng), "parentId": logbook_id, "snippetType": "paragraph",
            "createdAt": created, "updatedAt": _iso(when + rng.uniform(120, 7200)) if edited else created,
            "createdBy": author, "updatedBy": author, "tags": ([rng.choice(["setup", "overnight", "problem", "good run"])]
                                                               if rng.random() < 0.05 else []),
            "textcontent": "".join(body), "files": attached, "deleted": False,
            "readACL": ["p00000"], "updateACL": ["p00000"], "ownerGroup": "p00000"}


def _child(rng, parent, link):
    """A comment on a post, or the copy of a post that a reply quotes."""
    author = _pick(rng, AUTHORS)
    return {"id": _oid(rng), "parentId": parent["id"], "snippetType": "paragraph", "linkType": link,
            "createdAt": parent["createdAt"], "updatedAt": parent["createdAt"], "createdBy": author,
            "updatedBy": author, "textcontent": f"<p>{_sentence(rng)}</p>" if link == "comment" else parent["textcontent"],
            "files": [] if link == "comment" else parent["files"], "deleted": False, "tags": []}


