class Canvas:
    """A small RGB picture: lines, boxes, text and a colour map, written out as a PNG."""

    def __init__(self, width, height, colour=WHITE):
        self.w, self.h = width, height
        self.px = bytearray(bytes(colour) * (width * height))

    def set(self, x, y, colour):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i:i + 3] = bytes(colour)

    def box(self, x0, y0, x1, y1, colour, fill=False):
        x0, x1 = sorted((int(x0), int(x1)))
        y0, y1 = sorted((int(y0), int(y1)))
        if fill:
            for y in range(y0, y1 + 1):
                for x in range(x0, x1 + 1):
                    self.set(x, y, colour)
            return
        for x in range(x0, x1 + 1):
            self.set(x, y0, colour)
            self.set(x, y1, colour)
        for y in range(y0, y1 + 1):
            self.set(x0, y, colour)
            self.set(x1, y, colour)

    def line(self, x0, y0, x1, y1, colour, thick=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            for o in range(thick):
                self.set(x0, y0 + o, colour)
                if thick > 1:
                    self.set(x0 + o, y0, colour)
            if x0 == x1 and y0 == y1:
                return
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def mark(self, x, y, colour, size=2):
        self.box(x - size, y - size, x + size, y + size, colour, fill=True)

    def text(self, x, y, words, colour=BLACK, scale=1):
        """Upper-case 5x7 text; anything the font does not have becomes a space."""
        for ch in str(words).upper():
            rows = FONT.get(ch, FONT[" "])
            for r in range(7):
                bits = int(rows[r * 2:r * 2 + 2], 16)
                for c in range(5):
                    if bits & (1 << (4 - c)):
                        self.box(x + c * scale, y + r * scale, x + c * scale + scale - 1, y + r * scale + scale - 1,
                                 colour, fill=True)
            x += 6 * scale

    def png(self):
        raw = bytearray()
        for y in range(self.h):
            raw.append(0)                                   # no filter for this row
            raw += self.px[y * self.w * 3:(y + 1) * self.w * 3]

        def chunk(kind, data):
            return (struct.pack(">I", len(data)) + kind + data
                    + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))

        return (b"\x89PNG\r\n\x1a\n"
                + chunk(b"IHDR", struct.pack(">IIBBBBB", self.w, self.h, 8, 2, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(bytes(raw), 6))
                + chunk(b"IEND", b""))


def heat(v):
    """A value in 0..1 as a colour, dark blue through green to yellow."""
    stops = [(0.0, (34, 20, 90)), (0.35, (33, 110, 140)), (0.65, (60, 170, 100)),
             (0.85, (170, 205, 60)), (1.0, (250, 232, 90))]
    v = min(1.0, max(0.0, v))
    for (a, ca), (b, cb) in zip(stops, stops[1:]):
        if v <= b:
            f = (v - a) / (b - a)
            return tuple(int(ca[i] + (cb[i] - ca[i]) * f) for i in range(3))
    return stops[-1][1]


# -- the figures --------------------------------------------------------------------------

def _axes(c, title, xlabel, ylabel, x0=46, y0=18, x1=None, y1=None):
    x1 = c.w - 14 if x1 is None else x1
    y1 = c.h - 30 if y1 is None else y1
    for i in range(1, 5):                                   # a faint grid, as a plot has
        c.line(x0, y0 + (y1 - y0) * i // 5, x1, y0 + (y1 - y0) * i // 5, FAINT)
        c.line(x0 + (x1 - x0) * i // 5, y0, x0 + (x1 - x0) * i // 5, y1, FAINT)
    c.box(x0, y0, x1, y1, GREY)
    c.text(x0, 4, title[:34], BLACK)
    c.text((x0 + x1) // 2 - len(xlabel) * 3, c.h - 11, xlabel, GREY)
    c.text(2, 4, ylabel[:7], GREY)        # above the numbers down the side, not across them
    return x0, y0, x1, y1


def _ticks(c, x0, y0, x1, y1, lo, hi, vlo, vhi):
    for i in range(6):
        x = x0 + (x1 - x0) * i // 5
        c.line(x, y1, x, y1 + 3, GREY)
        label = f"{lo + (hi - lo) * i / 5:.0f}"
        # the last one ends at the axis, so a long number is not cut off by the edge
        c.text(x - (len(label) * 6 - 2 if i == 5 else len(label) * 3), y1 + 6, label, GREY)
    for i in range(6):
        y = y1 - (y1 - y0) * i // 5
        c.line(x0 - 3, y, x0, y, GREY)
        c.text(x0 - 26, y - 3, f"{vlo + (vhi - vlo) * i / 5:.0f}", GREY)


def scan_figure(rng, w=460, h=330):
    """A scan: a curve with points and error bars, the sort of thing a motor scan gives."""
    c = Canvas(w, h)
    x0, y0, x1, y1 = _axes(c, f"scan {rng.randint(100, 999)} {rng.choice(THINGS)}",
                           f"position ({rng.choice(['mm', 'ps', 'deg', 'ev'])})", "counts")
    n = rng.randint(18, 40)
    centre, width = rng.uniform(0.3, 0.7), rng.uniform(0.06, 0.25)
    shape = rng.choice(["peak", "edge", "dip", "two peaks"])
    top = rng.uniform(0.55, 0.95)
    pts = []
    for i in range(n):
        t = i / (n - 1)
        if shape == "peak":
            v = top * math.exp(-((t - centre) ** 2) / (2 * width ** 2))
        elif shape == "dip":
            v = top - top * 0.9 * math.exp(-((t - centre) ** 2) / (2 * width ** 2))
        elif shape == "edge":
            v = top / (1 + math.exp(-(t - centre) / max(width, 0.02)))
        else:
            v = top * (math.exp(-((t - centre + 0.18) ** 2) / (2 * width ** 2))
                       + 0.7 * math.exp(-((t - centre - 0.18) ** 2) / (2 * width ** 2)))
        v = max(0.02, v + rng.gauss(0, 0.035))
        pts.append((x0 + (x1 - x0) * t, y1 - (y1 - y0) * v))
    colour = rng.choice(INK)
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        c.line(ax, ay, bx, by, colour)
    for px, py in pts:
        c.mark(px, py, colour, 1)
        err = rng.uniform(3, 11)
        c.line(px, py - err, px, py + err, colour)
    lo = rng.uniform(-30, 10)
    _ticks(c, x0, y0, x1, y1, lo, lo + rng.uniform(5, 60), 0, rng.choice([100, 500, 1000, 5000]))
    return c.png()


def image_figure(rng, w=400, h=330):
    """A detector frame: a spot, some rings and noise, with a colour bar."""
    c = Canvas(w, h, (12, 10, 25))
    x0, y0, x1, y1 = 40, 20, w - 54, h - 30
    cx, cy = rng.uniform(0.3, 0.7), rng.uniform(0.3, 0.7)
    s = rng.uniform(0.04, 0.13)
    rings = rng.random() < 0.4
    for y in range(y0, y1):
        for x in range(x0, x1):
            u, v = (x - x0) / (x1 - x0), (y - y0) / (y1 - y0)
            r2 = (u - cx) ** 2 + (v - cy) ** 2
            val = math.exp(-r2 / (2 * s * s))
            if rings:
                val += 0.35 * math.exp(-((math.sqrt(r2) - 0.28) ** 2) / 0.002)
                val += 0.2 * math.exp(-((math.sqrt(r2) - 0.42) ** 2) / 0.0015)
            val += 0.08 * rng.random() + 0.05
            c.set(x, y, heat(val))
    c.box(x0, y0, x1, y1, GREY)
    for i in range(y0, y1):                                  # the colour bar
        c.box(x1 + 8, i, x1 + 22, i, heat(1 - (i - y0) / (y1 - y0)), fill=True)
    c.box(x1 + 8, y0, x1 + 22, y1, GREY)
    c.text(x0, 4, f"frame {rng.randint(1000, 9999)} {rng.randint(1, 60)} shots", WHITE)
    c.text(x0, h - 12, "pixel", (180, 180, 190))
    c.text(2, y0, "pixel", (180, 180, 190))
    c.line(x0 + (x1 - x0) * cx, y0, x0 + (x1 - x0) * cx, y1, (255, 255, 255))
    c.line(x0, y0 + (y1 - y0) * cy, x1, y0 + (y1 - y0) * cy, (255, 255, 255))
    return c.png()


def trace_figure(rng, w=520, h=260):
    """A long trace against time, with a step somewhere in it."""
    c = Canvas(w, h)
    x0, y0, x1, y1 = _axes(c, f"{rng.choice(THINGS)} against time", "minutes", "value")
    step_at = rng.uniform(0.3, 0.8)
    level, drift = rng.uniform(0.3, 0.6), rng.uniform(-0.1, 0.1)
    last = None
    for i in range(x1 - x0):
        t = i / (x1 - x0)
        v = level + drift * t + (0.25 if t > step_at else 0) + rng.gauss(0, 0.02)
        px, py = x0 + i, y1 - (y1 - y0) * min(0.98, max(0.02, v))
        if last:
            c.line(last[0], last[1], px, py, INK[0])
        last = (px, py)
    c.line(x0 + (x1 - x0) * step_at, y0, x0 + (x1 - x0) * step_at, y1, INK[1])
    _ticks(c, x0, y0, x1, y1, 0, rng.choice([30, 60, 120]), 0, rng.choice([10, 50, 100]))
    return c.png()


def spectrum_figure(rng, w=480, h=300):
    """A spectrum: a few peaks on a sloping background."""
    c = Canvas(w, h)
    x0, y0, x1, y1 = _axes(c, "spectrum " + rng.choice(["before", "after", "difference"]),
                           "energy (ev)", "signal")
    peaks = [(rng.uniform(0.1, 0.9), rng.uniform(0.2, 0.9), rng.uniform(0.01, 0.05)) for _ in range(rng.randint(2, 5))]
    last = None
    for i in range(x1 - x0):
        t = i / (x1 - x0)
        v = 0.08 + 0.15 * t + sum(a * math.exp(-((t - p) ** 2) / (2 * s * s)) for p, a, s in peaks)
        v += rng.gauss(0, 0.012)
        px, py = x0 + i, y1 - (y1 - y0) * min(0.98, max(0.02, v))
        if last:
            c.line(last[0], last[1], px, py, INK[2])
        last = (px, py)
    for p, a, _s in peaks:
        px = x0 + (x1 - x0) * p
        py = y1 - (y1 - y0) * min(0.98, a + 0.1 + 0.15 * p)
        c.line(px, py - 14, px, py - 4, GREY)
        c.text(px - 14, py - 24, f"{rng.uniform(500, 12000):.0f}", GREY)
    _ticks(c, x0, y0, x1, y1, rng.uniform(500, 9000), rng.uniform(9500, 12000), 0, 100)
    return c.png()


def camera_figure(rng, w=420, h=300):
    """A camera picture: a bright patch, a crosshair, a scale bar."""
    c = Canvas(w, h, (30, 30, 34))
    cx, cy = rng.uniform(0.35, 0.65), rng.uniform(0.35, 0.65)
    s = rng.uniform(0.07, 0.2)
    for y in range(h):
        for x in range(w):
            u, v = x / w, y / h
            g = math.exp(-(((u - cx) ** 2 + (v - cy) ** 2) / (2 * s * s)))
            g = min(1.0, g * rng.uniform(0.9, 1.1) + 0.06 * rng.random())
