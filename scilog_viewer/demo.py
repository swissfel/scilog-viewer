    c.line(int(w * cx), 0, int(w * cx), h, (255, 90, 60))
    c.line(0, int(h * cy), w, int(h * cy), (255, 90, 60))
    c.box(w - 90, h - 18, w - 20, h - 15, (255, 255, 255), fill=True)
    c.text(w - 90, h - 32, f"{rng.randint(50, 500)} um", (255, 255, 255))
    c.text(8, 8, f"cam {rng.randint(1, 8)} exposure {rng.randint(1, 900)} us", (255, 255, 255))
    return c.png()


