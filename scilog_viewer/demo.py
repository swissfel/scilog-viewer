def _fake_token(email="demo@example.org", name="Demo User"):
    """A token-shaped string so the page can say who is reading; it opens no door
    anywhere -- nothing is ever sent to SciLog in demo mode."""
    body = json.dumps({"name": name, "email": email, "roles": ["p00000"],
                       "exp": int(time.time()) + 365 * 86400}).encode()
    return "x." + base64.urlsafe_b64encode(body).decode().rstrip("=") + ".y"


class DemoReader:
    """What scilog_viewer.server.Store asks of a reader, answered out of a folder
    made by make(). Read-only: the viewer shows the logbook, writing is not on."""

    def __init__(self, where=None):
        self.where = Path(where or DEFAULT_DIR)
        made = json.loads((self.where / "logbook.json").read_text())
        self.book = made["logbook"]
        self.rows = made["posts"]
        self._tasks = made.get("tasks") or []
        self.files = made.get("files") or {}
        self.token = _fake_token()
        self.identity = f"{logs_scilog.describe(self.token).split(',')[0]} (made-up logbook, no SciLog)"
        self.url = "demo://logbook"

    # -- what the store reads
    def logbooks(self, location=None, pgroup=None, name=None):
        b = self.book
        return [{"id": b["id"], "name": b["name"], "pgroup": b["ownerGroup"], "location": b["location"],
                 "private": False, "touched": b["touchedAt"], "description": b.get("description", "")}]

    def logbook(self, logbook_id):
        return dict(self.book)

    def _with_children(self, rows, children):
        """Copies: the store marks up what it is given (a reply's quote, for one)."""
        return [dict(r) if children else {k: v for k, v in r.items() if k != "subsnippets"} for r in rows]

    def posts(self, logbook_id, updated_after=None, limit=100000, children=False):
        rows = [r for r in self.rows if r["parentId"] == logbook_id]
        if updated_after:
            rows = [r for r in rows if r["updatedAt"] > updated_after]
        return self._with_children(rows[:limit], children)

    def newest_posts(self, logbook_id, n, before=None, children=False):
        rows = [r for r in self.rows if r["parentId"] == logbook_id]
        if before:
            rows = [r for r in rows if r["createdAt"] <= before]
        return self._with_children(rows[max(0, len(rows) - n):], children)

    def children_since(self, updated_after, limit=2000):
        return []

    def tasks(self, logbook_id):
        return [dict(t) for t in self._tasks if t["parentId"] == logbook_id]

    def views(self, parent_ids):
        return []

    def image(self, file_id):
        return self._bytes(file_id), "image/png"

    def file(self, file_id):
        held = self.files.get(file_id) or {}
        name = held.get("name") or f"{file_id}.bin"
        if (held.get("type") or "").endswith("json"):
            return json.dumps({"made_up": True, "file": name,
                               "values": [round(random.Random(file_id).uniform(0, 1), 4) for _ in range(32)]}
                              ).encode(), "application/json", name
        return self._bytes(file_id), held.get("type") or "application/octet-stream", name

    def _bytes(self, file_id):
        held = self.files.get(file_id) or {}
        path = held.get("path")
        if not path:
            raise FileNotFoundError(f"{file_id} is not a file of this made-up logbook")
        return (self.where / path).read_bytes()

    # -- writing: not here
    def _no(self, *_a, **_k):
        raise PermissionError("this is a made-up logbook: nothing is written to it")

    create_post = update_post = delete_post = _no
    create_task = update_task = delete_task = _no
    update_view = delete_view = upload_file = set_read_acl = _no
    post = view = file_snippet = _no


def open_demo(where=None, make_if_missing=True, quiet=False):
    """The reader for a demo logbook, making one first if that folder has none."""
    where = Path(where or DEFAULT_DIR)
    if make_if_missing and not (where / "logbook.json").exists():
        if not quiet:
            print(f"making a logbook to look at in {where} (once; a few seconds) ...", flush=True)
        make(where, quiet=quiet)
    return DemoReader(where)
